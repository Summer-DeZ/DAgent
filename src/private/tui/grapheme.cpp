// BMP 表的最高位标记 Extended_Pictographic（GB11）。
constexpr uint8_t k_extpict_bit = 0x80;

// 区间表按 lo 升序存放，二分查找。
bool in_sorted(const Range* a, std::size_t n, char32_t cp) noexcept {
    std::size_t lo = 0, hi = n;
    while (lo < hi) {
        const std::size_t mid = lo + (hi - lo) / 2;
        if (cp < a[mid].lo) {
            hi = mid;
        } else if (cp > a[mid].hi) {
            lo = mid + 1;
        } else {
            return true;
        }
    }
    return false;
}

template <std::size_t N>
bool in_sorted(const Range (&a)[N], char32_t cp) noexcept {
    return in_sorted(a, N, cp);
}

Gcb gcb_of_range(char32_t cp) noexcept {
    std::size_t lo = 0;
    std::size_t hi = std::size(kGcbRanges);
    while (lo < hi) {
        const std::size_t mid = lo + (hi - lo) / 2;
        if (cp < kGcbRanges[mid].lo) {
            hi = mid;
        } else if (cp > kGcbRanges[mid].hi) {
            lo = mid + 1;
        } else {
            return kGcbRanges[mid].gc;
        }
    }
    return Gcb::other;
}

void mark_range(std::array<uint8_t, 0x10000>& t, const Range& r,
                uint8_t value) noexcept {
    const auto lo = static_cast<std::size_t>(r.lo);
    const auto hi = static_cast<std::size_t>(std::min<char32_t>(r.hi, 0xFFFF));
    for (std::size_t cp = lo; cp <= hi; ++cp) {
        t[cp] = value;
    }
}

// 宽度表：BMP 一次构建（64KB），星面走区间二分。
const std::array<uint8_t, 0x10000>& bmp_width() noexcept {
    static const std::array<uint8_t, 0x10000> table = [] {
        std::array<uint8_t, 0x10000> t{};
        t.fill(1);
        // wide 最后写：与 joiner/zero 的区间重叠处以宽为准。
        for (const Range& r : kZero) mark_range(t, r, 0);
        for (const Range& r : kJoiner) mark_range(t, r, 0);
        for (const Range& r : kWide) mark_range(t, r, 2);
        return t;
    }();
    return table;
}

// GCB 表：低 4 位类别，最高位 Extended_Pictographic。
const std::array<uint8_t, 0x10000>& bmp_gcb() noexcept {
    static const std::array<uint8_t, 0x10000> table = [] {
        std::array<uint8_t, 0x10000> t{};
        for (const GcbRange& r : kGcbRanges) {
            const auto lo = static_cast<std::size_t>(r.lo);
            const auto hi =
                static_cast<std::size_t>(std::min<char32_t>(r.hi, 0xFFFF));
            for (std::size_t cp = lo; cp <= hi; ++cp) {
                t[cp] = static_cast<uint8_t>(r.gc);
            }
        }
        for (const Range& r : kExtPict) {
            const auto lo = static_cast<std::size_t>(r.lo);
            const auto hi =
                static_cast<std::size_t>(std::min<char32_t>(r.hi, 0xFFFF));
            for (std::size_t cp = lo; cp <= hi; ++cp) t[cp] |= k_extpict_bit;
        }
        return t;
    }();
    return table;
}

Gcb gcb_of(char32_t cp) noexcept {
    if (cp < 0x10000) return static_cast<Gcb>(bmp_gcb()[cp] & 0x0F);
    return gcb_of_range(cp);
}

bool is_extpict(char32_t cp) noexcept {
    if (cp < 0x10000) return (bmp_gcb()[cp] & k_extpict_bit) != 0;
    return in_sorted(kExtPict, cp);
}

