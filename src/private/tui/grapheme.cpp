// 码点显示宽度：0（组合记号/格式/控制）、1（半角）、2（全角/emoji）。
// Emoji_Presentation=Yes 与 EAW W/F 同为 2 列（§3.13）。
int char_width(char32_t cp) noexcept {
    if (cp < 0x10000) return bmp_width()[cp];
    if (in_sorted(kZero, cp) || in_sorted(kJoiner, cp)) return 0;
    if (in_sorted(kWide, cp)) return 2;
    return 1;
}

char32_t decode_utf8(std::string_view& s) noexcept {
    const unsigned char b0 = static_cast<unsigned char>(s[0]);
    std::size_t len = 0;
    char32_t cp = 0;
    if (b0 < 0x80) {
        len = 1;
        cp = b0;
    } else if ((b0 & 0xE0) == 0xC0) {
        len = 2;
        cp = b0 & 0x1F;
    } else if ((b0 & 0xF0) == 0xE0) {
        len = 3;
        cp = b0 & 0x0F;
    } else if ((b0 & 0xF8) == 0xF0) {
        len = 4;
        cp = b0 & 0x07;
    } else {
        s.remove_prefix(1);
        return 0xFFFD;
    }
    for (std::size_t i = 1; i < len; ++i) {
        // 末尾截断：已有的续字节整体作废；遇到非续字节：只丢首字节，
        // 其后的合法内容保留。
        if (i >= s.size()) {
            s.remove_prefix(s.size());
            return 0xFFFD;
        }
        const unsigned char b = static_cast<unsigned char>(s[i]);
        if ((b & 0xC0) != 0x80) {
            s.remove_prefix(1);
            return 0xFFFD;
        }
        cp = (cp << 6) | (b & 0x3F);
    }
    // 过长编码、代理区、越界一律按非法处理。
    if ((len == 2 && cp < 0x80) || (len == 3 && cp < 0x800) ||
        (len == 4 && cp < 0x10000) || (cp >= 0xD800 && cp <= 0xDFFF) ||
        cp > 0x10FFFF) {
        s.remove_prefix(1);
        return 0xFFFD;
    }
    s.remove_prefix(len);
    return cp;
}

std::size_t encode_utf8(char32_t cp, char (&out)[4]) noexcept {
    if (cp < 0x80) {
        out[0] = static_cast<char>(cp);
        return 1;
    }
    if (cp < 0x800) {
        out[0] = static_cast<char>(0xC0 | (cp >> 6));
        out[1] = static_cast<char>(0x80 | (cp & 0x3F));
        return 2;
    }
    if (cp < 0x10000) {
        out[0] = static_cast<char>(0xE0 | (cp >> 12));
        out[1] = static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out[2] = static_cast<char>(0x80 | (cp & 0x3F));
        return 3;
    }
    if (cp <= 0x10FFFF) {
        out[0] = static_cast<char>(0xF0 | (cp >> 18));
        out[1] = static_cast<char>(0x80 | ((cp >> 12) & 0x3F));
        out[2] = static_cast<char>(0x80 | ((cp >> 6) & 0x3F));
        out[3] = static_cast<char>(0x80 | (cp & 0x3F));
        return 4;
    }
    out[0] = ' ';
    return 1;
}

